#!/usr/bin/env python3
"""devloop: poll a GitHub Project and run Claude Code on stories that are ready.

Each run (devloop.timer, every 30 minutes) does three passes:

  1. sync       "In review" stories: PR merged -> Done and the issue is closed.
                PR closed without merging -> Needs human.
  2. implement  "Ready" stories: a fresh worktree off the story's epic branch.
                Claude edits and tests; devloop commits, pushes claude/issue-<n>
                and opens a PR into the epic branch. Status -> In review.
  3. refine     "Needs refinement" stories: Claude reads the repo read-only and
                writes a spec. devloop updates the issue body and moves it to
                Ready, or to Needs human with questions that @mention you.

Every Claude run is a new session, so nothing carries over between stories.
Claude never sees the GitHub token: it reads a prompt and writes result.json,
and devloop makes every GitHub write itself.

Standard library only. Python 3.11+ (tomllib).
"""

