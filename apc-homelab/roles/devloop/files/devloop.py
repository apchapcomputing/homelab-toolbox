class ClaudeFailed(Exception):
    pass


def claude_env(cfg: Config) -> dict:
    keep = ("HOME", "PATH", "LANG", "LC_ALL", "USER", "LOGNAME", "TMPDIR")
    env = {k: os.environ[k] for k in keep if k in os.environ}
    env["CI"] = "1"
    return env


def run_claude(cfg: Config, mode: str, cwd: Path, prompt: str, run_dir: Path) -> dict:
    result = run_dir / "result.json"
    (run_dir / "prompt.txt").write_text(prompt)
    wt_rule = f"/{cwd}/**"           # absolute paths take a leading // in permission rules
    allowed = ["Read", "Glob", "Grep", f"Write(/{result})"]
    if mode == "refine":
        tools = "Read,Glob,Grep,Write"
        timeout, turns = cfg.refine_timeout_min, cfg.refine_max_turns
    else:
        tools = "Read,Glob,Grep,Edit,Write,Bash"
        allowed += [f"Edit({wt_rule})", f"Write({wt_rule})"]
        allowed += [f"Bash({b})" for b in cfg.allowed_bash]
        timeout, turns = cfg.implement_timeout_min, cfg.implement_max_turns
    denied = [f"Edit(/{cwd}/{p}**)" for p in (".github/", ".env")] + [f"Edit(/{cwd}/**/CLAUDE.md)"]
    cmd = [cfg.claude_bin, "-p", "--output-format", "json", "--strict-mcp-config",
           "--tools", tools,
           "--allowedTools", ",".join(allowed),
           "--disallowedTools", ",".join(denied),
           "--max-turns", str(turns),
           # Non-variadic option last, so the prompt is not read as another tool name.
           "--permission-mode", "dontAsk",
           prompt]
    started = time.monotonic()
    try:
        proc = subprocess.run(cmd, cwd=cwd, env=claude_env(cfg), text=True, stdin=subprocess.DEVNULL,
                              capture_output=True, timeout=timeout * 60)
    except subprocess.TimeoutExpired:
        raise ClaudeFailed(f"timed out after {timeout} minutes") from None
    (run_dir / "claude.json").write_text(proc.stdout)
    (run_dir / "claude.err").write_text(proc.stderr)
    log(f"  claude exited {proc.returncode} after {int(time.monotonic() - started)}s")
    if not result.is_file():
        tail = (proc.stderr or proc.stdout).strip()[-400:]
        raise ClaudeFailed(f"no result.json (exit {proc.returncode}): {tail}")
    try:
        data = json.loads(result.read_text())
    except json.JSONDecodeError as e:
        raise ClaudeFailed(f"result.json is not valid JSON: {e}") from None
    ok = {"refine": ("ready", "needs_human"), "implement": ("done", "needs_human")}[mode]
    if data.get("outcome") not in ok:
        raise ClaudeFailed(f"result.json outcome {data.get('outcome')!r} is not one of {ok}")
    if mode == "refine" and not str(data.get("spec", "")).strip():
        raise ClaudeFailed("result.json has an empty spec")
    if data["outcome"] == "needs_human" and not data.get("questions"):
        raise ClaudeFailed("outcome needs_human but no questions")
    return data


# ---------------------------------------------------------------- helpers

def original_request(body: str) -> str:
    if ORIG_START in body and ORIG_END in body:
        return body.split(ORIG_START, 1)[1].split(ORIG_END, 1)[0].strip()
    return body.strip()


def compose_body(spec: str, body: str) -> str:
    return (f"{spec.strip()}\n\n<details><summary>Original request</summary>\n\n"
            f"{ORIG_START}\n{original_request(body)}\n{ORIG_END}\n\n</details>\n")


DEP_RE = re.compile(r"(?:(?P<repo>[\w.-]+/[\w.-]+))?#(?P<num>\d+)")


def dependencies(body: str, default_repo: str) -> list[tuple[str, int]]:
    """Issue refs listed under the '## Dependencies' heading."""
    m = re.search(r"^##\s*Dependencies\s*$(.*?)(?=^##\s|\Z)", body, re.M | re.S)
    if not m:
        return []
    return [(d.group("repo") or default_repo, int(d.group("num"))) for d in DEP_RE.finditer(m.group(1))]


def format_comments(comments: list[dict], trusted: set[str]) -> str:
    parts = []
    for c in comments:
        login = (c.get("user") or {}).get("login", "")
        if login not in trusted:
            continue
        who = f"{login} (devloop)" if MARK in (c.get("body") or "") else login
        parts.append(f"--- {who}, {c.get('created_at', '')}\n{c.get('body', '').replace(MARK, '').strip()}")
    return "\n\n".join(parts) or "(none)"


def questions_comment(cfg: Config, mode: str, questions: list[dict]) -> str:
    lines = [f"@{cfg.human_login} devloop needs answers before it can {mode} this story.", ""]
    for i, q in enumerate(questions, 1):
        lines.append(f"{i}. {q.get('question', '').strip()}")
        if q.get("default"):
            lines.append(f"   Suggested default: {q['default'].strip()}")
    lines += ["", f"Reply here (\"defaults are fine\" works), then set Status to "
                  f"**{cfg.status['refine']}**."]
    return "\n".join(lines)


def changed_paths(git: Git, wt: Path) -> list[str]:
    out = git.run("status", "--porcelain", "--untracked-files=all", cwd=wt)
    return [line[3:].split(" -> ")[-1] for line in out.splitlines() if line.strip()]


class State:
    def __init__(self, path: Path):
        self.path = path
        self.data = json.loads(path.read_text()) if path.is_file() else {}

    def failures(self, key: str) -> int:
        return self.data.get(key, {}).get("failures", 0)

    def fail(self, key: str) -> int:
        self.data.setdefault(key, {})["failures"] = self.failures(key) + 1
        self.save()
        return self.failures(key)

    def clear(self, key: str) -> None:
        if self.data.pop(key, None) is not None:
            self.save()

    def save(self) -> None:
        tmp = self.path.with_suffix(".tmp")
        tmp.write_text(json.dumps(self.data, indent=2))
        tmp.replace(self.path)


# ---------------------------------------------------------------- the loop

class Devloop:
    def __init__(self, cfg: Config, gh: GitHub, git: Git, dry_run: bool):
        self.cfg, self.gh, self.git, self.dry = cfg, gh, git, dry_run
        self.project = Project(gh, cfg)
        self.workdir = Path(cfg.workdir)
        self.state = State(self.workdir / "state.json")
        self.trusted = set(cfg.trusted_authors)
        self.stop = False   # set after a Claude failure, so usage limits don't burn through the queue

    def by_status(self, key: str) -> list[Story]:
        name = self.cfg.status[key]
        return [s for s in self.project.stories if s.status == name and s.state == "OPEN"]

    def trusted_story(self, s: Story) -> bool:
        if s.author in self.trusted:
            return True
        log(f"{s.key}: skipped, author {s.author!r} is not in trusted_authors")
        return False

    def run_dir(self, s: Story, mode: str) -> Path:
        stamp = dt.datetime.now().strftime("%Y%m%d-%H%M%S")
        d = self.workdir / "runs" / f"{stamp}-{s.repo.replace('/', '__')}-{s.number}-{mode}"
        d.mkdir(parents=True, exist_ok=True)
        return d

    def failed(self, s: Story, mode: str, revert_to: str, reason: str, run_dir: Path) -> None:
        count = self.state.fail(s.key)
        log(f"  {mode} failed ({count}/{self.cfg.max_failures}): {reason}")
        self.stop = True
        if count >= self.cfg.max_failures:
            self.gh.comment(s.repo, s.number,
                            f"@{self.cfg.human_login} devloop could not {mode} this story after "
                            f"{count} tries.\n\nLast error: `{reason[:300]}`\n\nRun log on the server: "
                            f"`{run_dir}`\n\nFix the cause, then set Status to **{self.cfg.status[revert_to]}**.")
            self.project.set_status(s, "human")
            self.state.clear(s.key)
        else:
            self.project.set_status(s, revert_to)

    # 1. sync
    def sync_reviews(self) -> None:
        for s in self.by_status("review"):
            pr = self.gh.find_pr(s.repo, s.branch)
            if pr is None:
                log(f"{s.key}: In review but no PR on {s.branch}")
                if not self.dry:
                    self.gh.comment(s.repo, s.number, f"@{self.cfg.human_login} this story is In review "
                                    f"but there is no PR from `{s.branch}`.")
                    self.project.set_status(s, "human")
            elif pr.get("merged_at"):
                log(f"{s.key}: PR #{pr['number']} merged into {pr['base']['ref']} -> Done")
                if not self.dry:
                    self.project.set_status(s, "done")
                    self.gh.comment(s.repo, s.number, f"Merged into `{pr['base']['ref']}` by #{pr['number']}.")
                    self.gh.close(s.repo, s.number)
            elif pr["state"] == "closed":
                log(f"{s.key}: PR #{pr['number']} closed without merging -> Needs human")
                if not self.dry:
                    self.gh.comment(s.repo, s.number, f"@{self.cfg.human_login} #{pr['number']} was closed "
                                    f"without merging. Say what should change, then set Status to "
                                    f"**{self.cfg.status['refine']}** or **{self.cfg.status['ready']}**.")
                    self.project.set_status(s, "human")

    # 2. implement
    def blocked_by(self, s: Story) -> list[str]:
        open_deps = []
        for repo, num in dependencies(s.body, s.repo):
            if (repo, num) == (s.repo, s.number):
                continue
            try:
                if self.gh.issue_state(repo, num) == "open":
                    open_deps.append(f"{repo}#{num}")
            except GitHubError as e:
                open_deps.append(f"{repo}#{num} ({e.status})")
        return open_deps

    def implement(self) -> None:
        done = 0
        for s in self.by_status("ready"):
            if self.stop or done >= self.cfg.max_implement_per_run:
                return
            if not self.trusted_story(s):
                continue
            blockers = self.blocked_by(s)
            if blockers:
                log(f"{s.key}: Ready but blocked by {', '.join(blockers)}")
                continue
            log(f"{s.key}: implement '{s.title}' -> PR into {s.base}")
            done += 1
            if self.dry:
                continue
            self.implement_one(s)

    def implement_one(self, s: Story) -> None:
        self.project.set_status(s, "working")
        run_dir = self.run_dir(s, "implement")
        clone = wt = None
        try:
            clone = self.git.sync(s.repo)
            self.git.ensure_epic(clone, s)
            wt = self.git.worktree(clone, s, "implement")
            prompt = IMPLEMENT_PROMPT.format(
                repo=s.repo, branch=s.branch, base=s.base, number=s.number, title=s.title,
                extra=self.cfg.extra_context, body=s.body,
                comments=format_comments(self.gh.comments(s.repo, s.number), self.trusted),
                result=run_dir / "result.json")
            result = run_claude(self.cfg, "implement", wt, prompt, run_dir)
            if result["outcome"] == "needs_human":
                self.gh.comment(s.repo, s.number, questions_comment(self.cfg, "implement", result["questions"]))
                self.project.set_status(s, "human")
                self.state.clear(s.key)
                return
            paths = changed_paths(self.git, wt)
            if not paths:
                raise ClaudeFailed("Claude reported done but changed no files")
            bad = [p for p in paths if p.startswith(PROTECTED_PATHS) or p.endswith("CLAUDE.md")]
            if bad:
                raise ClaudeFailed(f"changed protected files: {', '.join(bad)}")
            self.git.run("add", "-A", cwd=wt)
            msg = (result.get("commit_message") or s.title).strip().splitlines()[0][:100]
            self.git.run("commit", "-q", "-m", msg, "-m", f"Refs {s.url}", cwd=wt)
            self.git.run("push", "--force", "origin", f"HEAD:refs/heads/{s.branch}", cwd=wt)
            pr = self.gh.find_pr(s.repo, s.branch)
            if pr is None or pr["state"] != "open":
                body = (f"{result.get('pr_body', '').strip()}\n\nRefs #{s.number}\n\n"
                        f"Merging into `{s.base}` does not close the story. devloop closes it after the merge.")
                pr = self.gh.open_pr(s.repo, s.branch, s.base, (result.get("pr_title") or msg)[:120], body)
                if self.cfg.auto_merge_epic and s.base != s.default_branch:
                    try:
                        self.gh.enable_auto_merge(pr["node_id"])
                    except GitHubError as e:
                        log(f"  auto-merge not enabled: {e}")
            self.gh.comment(s.repo, s.number, f"Opened {pr['html_url']} into `{s.base}`.")
            self.project.set_status(s, "review")
            self.state.clear(s.key)
            log(f"  opened {pr['html_url']}")
        except (ClaudeFailed, RuntimeError, GitHubError, OSError) as e:
            self.failed(s, "implement", "ready", str(e), run_dir)
        finally:
            if clone and wt:
                self.git.remove_worktree(clone, wt)

    # 3. refine
    def refine(self) -> None:
        done = 0
        for s in self.by_status("refine"):
            if self.stop or done >= self.cfg.max_refine_per_run:
                return
            if not self.trusted_story(s):
                continue
            log(f"{s.key}: refine '{s.title}'")
            done += 1
            if self.dry:
                continue
            self.refine_one(s)

    def refine_one(self, s: Story) -> None:
        run_dir = self.run_dir(s, "refine")
        clone = wt = None
        try:
            clone = self.git.sync(s.repo)
            wt = self.git.worktree(clone, s, "refine")
            prompt = REFINE_PROMPT.format(
                repo=s.repo, base=s.base, number=s.number, title=s.title,
                extra=self.cfg.extra_context, body=s.body,
                comments=format_comments(self.gh.comments(s.repo, s.number), self.trusted),
                result=run_dir / "result.json")
            result = run_claude(self.cfg, "refine", wt, prompt, run_dir)
            self.gh.set_body(s.repo, s.number, compose_body(result["spec"], s.body))
            if result["outcome"] == "ready":
                self.project.set_status(s, "ready")
                log(f"  ready: {result.get('summary', '')}")
            else:
                self.gh.comment(s.repo, s.number, questions_comment(self.cfg, "refine", result["questions"]))
                self.project.set_status(s, "human")
                log(f"  needs human: {len(result['questions'])} question(s)")
            self.state.clear(s.key)
        except (ClaudeFailed, RuntimeError, GitHubError, OSError) as e:
            self.failed(s, "refine", "refine", str(e), run_dir)
        finally:
            if clone and wt:
                self.git.remove_worktree(clone, wt)

    def prune_runs(self) -> None:
        runs = self.workdir / "runs"
        if not runs.is_dir():
            return
        cutoff = time.time() - self.cfg.keep_run_days * 86400
        for d in runs.iterdir():
            if d.is_dir() and d.stat().st_mtime < cutoff:
                shutil.rmtree(d, ignore_errors=True)

    def run(self) -> None:
        self.project.load()
        counts = {k: len(self.by_status(k)) for k in ("refine", "ready", "review", "human")}
        log("project: " + ", ".join(f"{self.cfg.status[k]}={v}" for k, v in counts.items()))
        self.sync_reviews()
        self.implement()
        self.refine()
        if not self.dry:
            self.prune_runs()


def main() -> int:
    ap = argparse.ArgumentParser(description="Run Claude Code on GitHub Project stories that are ready.")
    ap.add_argument("--config", default="/etc/devloop/config.toml")
    ap.add_argument("--dry-run", action="store_true", help="list what would run; change nothing")
    args = ap.parse_args()

    cfg = Config.load(Path(args.config))
    workdir = Path(cfg.workdir)
    workdir.mkdir(parents=True, exist_ok=True)
    lock = open(workdir / "devloop.lock", "w")
    try:
        fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
    except BlockingIOError:
        log("devloop: the previous run is still going")
        return 0
    token = read_token()
    Devloop(cfg, GitHub(token), Git(cfg, token), args.dry_run).run()
    return 0


if __name__ == "__main__":
    sys.exit(main())
