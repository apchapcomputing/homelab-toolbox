# ---------------------------------------------------------------- config

class Config:
    def __init__(self, raw: dict):
        self.raw = raw

    def __getattr__(self, name):
        try:
            return self.raw[name]
        except KeyError:
            raise AttributeError(name) from None

    @classmethod
    def load(cls, path: Path) -> "Config":
        with open(path, "rb") as f:
            user = tomllib.load(f)
        merged = {**DEFAULTS, **user}
        merged["status"] = {**DEFAULTS["status"], **user.get("status", {})}
        for key in ("project_owner", "project_number", "human_login", "trusted_authors"):
            if not merged.get(key):
                sys.exit(f"devloop: config is missing '{key}'")
        if merged["owner_type"] not in ("user", "organization"):
            sys.exit("devloop: owner_type must be 'user' or 'organization'")
        return cls(merged)


def read_token() -> str:
    cred_dir = os.environ.get("CREDENTIALS_DIRECTORY")
    if cred_dir and (Path(cred_dir) / "github-token").is_file():
        return (Path(cred_dir) / "github-token").read_text().strip()
    if os.environ.get("DEVLOOP_GITHUB_TOKEN"):
        return os.environ["DEVLOOP_GITHUB_TOKEN"].strip()
    sys.exit("devloop: no GitHub token (systemd credential 'github-token' or DEVLOOP_GITHUB_TOKEN)")


