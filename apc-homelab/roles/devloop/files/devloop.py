class GitHubError(Exception):
    def __init__(self, status: int, message: str):
        super().__init__(f"HTTP {status}: {message}")
        self.status = status


class GitHub:
    API = "https://api.github.com"

    def __init__(self, token: str):
        self.token = token

    def _call(self, method: str, url: str, body=None):
        data = json.dumps(body).encode() if body is not None else None
        req = urllib.request.Request(url, data=data, method=method, headers={
            "Authorization": f"Bearer {self.token}",
            "Accept": "application/vnd.github+json",
            "X-GitHub-Api-Version": "2022-11-28",
            "User-Agent": "devloop",
            "Content-Type": "application/json",
        })
        for attempt in range(3):
            try:
                with urllib.request.urlopen(req, timeout=30) as resp:
                    raw = resp.read()
                    return json.loads(raw) if raw else None
            except urllib.error.HTTPError as e:
                text = e.read().decode(errors="replace")[:500]
                if e.code in (502, 503, 504) and attempt < 2:
                    time.sleep(5 * (attempt + 1))
                    continue
                raise GitHubError(e.code, text) from None
            except urllib.error.URLError:
                if attempt < 2:
                    time.sleep(5 * (attempt + 1))
                    continue
                raise

    def rest(self, method: str, path: str, body=None):
        return self._call(method, self.API + path, body)

    def graphql(self, query: str, variables: dict):
        out = self._call("POST", self.API + "/graphql", {"query": query, "variables": variables})
        if out.get("errors"):
            raise GitHubError(200, json.dumps(out["errors"])[:500])
        return out["data"]

    # REST helpers
    def comments(self, repo: str, number: int) -> list[dict]:
        out, page = [], 1
        while True:
            batch = self.rest("GET", f"/repos/{repo}/issues/{number}/comments?per_page=100&page={page}")
            out.extend(batch)
            if len(batch) < 100:
                return out
            page += 1

    def comment(self, repo: str, number: int, body: str) -> None:
        self.rest("POST", f"/repos/{repo}/issues/{number}/comments", {"body": f"{MARK}\n{body}{FOOTER}"})

    def set_body(self, repo: str, number: int, body: str) -> None:
        self.rest("PATCH", f"/repos/{repo}/issues/{number}", {"body": body})

    def close(self, repo: str, number: int) -> None:
        self.rest("PATCH", f"/repos/{repo}/issues/{number}", {"state": "closed", "state_reason": "completed"})

    def issue_state(self, repo: str, number: int) -> str:
        return self.rest("GET", f"/repos/{repo}/issues/{number}")["state"]

    def find_pr(self, repo: str, branch: str) -> dict | None:
        owner = repo.split("/")[0]
        head = urllib.parse.quote(f"{owner}:{branch}")
        prs = self.rest("GET", f"/repos/{repo}/pulls?head={head}&state=all&per_page=10")
        return prs[0] if prs else None

    def open_pr(self, repo: str, head: str, base: str, title: str, body: str) -> dict:
        return self.rest("POST", f"/repos/{repo}/pulls",
                         {"title": title, "head": head, "base": base, "body": body + FOOTER})

    def enable_auto_merge(self, pr_node_id: str) -> None:
        self.graphql(
            "mutation($id: ID!) { enablePullRequestAutoMerge(input: {pullRequestId: $id, mergeMethod: SQUASH}) { clientMutationId } }",
            {"id": pr_node_id},
        )


