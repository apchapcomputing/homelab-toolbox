PROJECT_QUERY = """
query($login: String!, $number: Int!, $after: String) {
  OWNER(login: $login) {
    projectV2(number: $number) {
      id
      fields(first: 50) { nodes {
        ... on ProjectV2SingleSelectField { id name options { id name } }
        ... on ProjectV2Field { id name }
      } }
      items(first: 100, after: $after) {
        pageInfo { hasNextPage endCursor }
        nodes {
          id
          isArchived
          fieldValues(first: 30) { nodes {
            ... on ProjectV2ItemFieldSingleSelectValue { name field { ... on ProjectV2FieldCommon { name } } }
            ... on ProjectV2ItemFieldTextValue { text field { ... on ProjectV2FieldCommon { name } } }
          } }
          content {
            __typename
            ... on Issue {
              number title body url state
              author { login }
              repository { nameWithOwner defaultBranchRef { name } }
            }
          }
        }
      }
    }
  }
}
"""

SET_STATUS = """
mutation($project: ID!, $item: ID!, $field: ID!, $option: String!) {
  updateProjectV2ItemFieldValue(input: {projectId: $project, itemId: $item, fieldId: $field,
                                        value: {singleSelectOptionId: $option}}) {
    projectV2Item { id }
  }
}
"""


@dataclasses.dataclass
class Story:
    item_id: str
    status: str
    epic_branch: str
    repo: str
    number: int
    title: str
    body: str
    url: str
    state: str
    author: str
    default_branch: str

    @property
    def key(self) -> str:
        return f"{self.repo}#{self.number}"

    @property
    def base(self) -> str:
        return self.epic_branch or self.default_branch

    @property
    def branch(self) -> str:
        return f"claude/issue-{self.number}"


class Project:
    def __init__(self, gh: GitHub, cfg: Config):
        self.gh, self.cfg = gh, cfg
        self.id = ""
        self.status_field_id = ""
        self.options: dict[str, str] = {}
        self.stories: list[Story] = []

    def load(self) -> None:
        query = PROJECT_QUERY.replace("OWNER", self.cfg.owner_type)
        after = None
        while True:
            data = self.gh.graphql(query, {"login": self.cfg.project_owner,
                                           "number": int(self.cfg.project_number), "after": after})
            proj = data[self.cfg.owner_type]["projectV2"]
            if proj is None:
                sys.exit("devloop: project not found, or the token cannot read it")
            self.id = proj["id"]
            for f in proj["fields"]["nodes"]:
                if f and f.get("name") == self.cfg.status_field and "options" in f:
                    self.status_field_id = f["id"]
                    self.options = {o["name"]: o["id"] for o in f["options"]}
            for node in proj["items"]["nodes"]:
                story = self._story(node)
                if story:
                    self.stories.append(story)
            page = proj["items"]["pageInfo"]
            if not page["hasNextPage"]:
                break
            after = page["endCursor"]
        if not self.status_field_id:
            sys.exit(f"devloop: project has no single-select field named '{self.cfg.status_field}'")
        missing = [s for s in self.cfg.status.values() if s not in self.options]
        if missing:
            sys.exit(f"devloop: add these options to the '{self.cfg.status_field}' field: {', '.join(missing)}")

    def _story(self, node: dict) -> Story | None:
        content = node.get("content") or {}
        if node.get("isArchived") or content.get("__typename") != "Issue":
            return None
        status = epic = ""
        for v in node["fieldValues"]["nodes"]:
            if not v or "field" not in v:
                continue
            name = v["field"].get("name")
            if name == self.cfg.status_field:
                status = v.get("name", "")
            elif name == self.cfg.epic_field:
                epic = (v.get("text") or "").strip()
        repo = content["repository"]
        return Story(
            item_id=node["id"], status=status, epic_branch=epic,
            repo=repo["nameWithOwner"], number=content["number"], title=content["title"],
            body=content.get("body") or "", url=content["url"], state=content["state"],
            author=(content.get("author") or {}).get("login", ""),
            default_branch=(repo.get("defaultBranchRef") or {}).get("name", "main"),
        )

    def set_status(self, story: Story, key: str) -> None:
        name = self.cfg.status[key]
        self.gh.graphql(SET_STATUS, {"project": self.id, "item": story.item_id,
                                     "field": self.status_field_id, "option": self.options[name]})
        story.status = name


