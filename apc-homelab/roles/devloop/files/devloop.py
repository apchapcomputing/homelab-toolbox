class Git:
    def __init__(self, cfg: Config, token: str):
        self.cfg = cfg
        cred = base64.b64encode(f"x-access-token:{token}".encode()).decode()
        # Passed through the environment, never written to .git/config and never given to Claude.
        self.env = {**os.environ, "GIT_TERMINAL_PROMPT": "0",
                    "GIT_CONFIG_COUNT": "1",
                    "GIT_CONFIG_KEY_0": f"http.{cfg.git_base_url}/.extraheader",
                    "GIT_CONFIG_VALUE_0": f"AUTHORIZATION: basic {cred}",
                    "GIT_AUTHOR_NAME": cfg.git_name, "GIT_AUTHOR_EMAIL": cfg.git_email,
                    "GIT_COMMITTER_NAME": cfg.git_name, "GIT_COMMITTER_EMAIL": cfg.git_email}

    def run(self, *args: str, cwd: Path | None = None) -> str:
        res = subprocess.run(["git", *args], cwd=cwd, env=self.env, text=True,
                             capture_output=True, timeout=900)
        if res.returncode != 0:
            raise RuntimeError(f"git {' '.join(args[:3])} failed: {res.stderr.strip()[-500:]}")
        return res.stdout

    def clone_path(self, repo: str) -> Path:
        return Path(self.cfg.workdir) / "repos" / repo.replace("/", "__")

    def sync(self, repo: str) -> Path:
        path = self.clone_path(repo)
        if not (path / ".git").exists():
            path.parent.mkdir(parents=True, exist_ok=True)
            self.run("clone", "--filter=blob:none", "--no-checkout",
                     f"{self.cfg.git_base_url}/{repo}.git", str(path))
        else:
            self.run("fetch", "--prune", "origin", cwd=path)
        self.run("worktree", "prune", cwd=path)
        return path

    def has_remote_branch(self, clone: Path, branch: str) -> bool:
        res = subprocess.run(["git", "rev-parse", "--verify", "--quiet", f"refs/remotes/origin/{branch}"],
                             cwd=clone, env=self.env, capture_output=True)
        return res.returncode == 0

    def ensure_epic(self, clone: Path, story: Story) -> None:
        """Create the epic branch from the default branch if it doesn't exist yet."""
        if story.base == story.default_branch or self.has_remote_branch(clone, story.base):
            return
        self.run("push", "origin", f"refs/remotes/origin/{story.default_branch}:refs/heads/{story.base}", cwd=clone)
        self.run("fetch", "origin", cwd=clone)
        log(f"  created epic branch {story.base} from {story.default_branch}")

    def worktree(self, clone: Path, story: Story, mode: str) -> Path:
        wt = Path(self.cfg.workdir) / "worktrees" / f"{story.repo.replace('/', '__')}-{story.number}-{mode}"
        self.remove_worktree(clone, wt)
        wt.parent.mkdir(parents=True, exist_ok=True)
        start = f"origin/{story.base}" if self.has_remote_branch(clone, story.base) else f"origin/{story.default_branch}"
        if mode == "implement":
            self.run("worktree", "add", "--force", "-B", story.branch, str(wt), start, cwd=clone)
        else:
            self.run("worktree", "add", "--force", "--detach", str(wt), start, cwd=clone)
        return wt

    def remove_worktree(self, clone: Path, wt: Path) -> None:
        if wt.exists():
            subprocess.run(["git", "worktree", "remove", "--force", str(wt)], cwd=clone,
                           env=self.env, capture_output=True)
            shutil.rmtree(wt, ignore_errors=True)
        subprocess.run(["git", "worktree", "prune"], cwd=clone, env=self.env, capture_output=True)


